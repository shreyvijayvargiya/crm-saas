export function findSubscription(id) {
	return SUBSCRIPTIONS.find((s) => s.id === id) ?? null;
}

export function findSubscriptionEvents(subscriptionId) {
	return SUBSCRIPTION_EVENTS[subscriptionId] ?? [];
}

export function findPlan(id) {
	return SUBSCRIPTION_PLANS.find((p) => p.id === id) ?? null;
}

export function getUpgradePlans(currentPlanId) {
	return SUBSCRIPTION_PLANS.filter(
		(p) => p.status === "Active" && p.id !== currentPlanId
	);
}

